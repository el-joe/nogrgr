<?php

namespace App\Modules\Commerce\Http\Requests\Orders;

use Illuminate\Foundation\Http\FormRequest;

/**
 * Shipping queue "Mark shipped" for the selected rows (order_facts ids).
 */
class BulkShipRequest extends FormRequest
{
    public function authorize(): bool
    {
        return true;
    }

    /**
     * @return array<string, mixed>
     */
    public function rules(): array
    {
        return [
            'ids' => ['required', 'array', 'min:1', 'max:100'],
            'ids.*' => ['integer', 'distinct'],
        ];
    }

    /**
     * @return list<int>
     */
    public function ids(): array
    {
        return array_values(array_map('intval', (array) $this->validated('ids')));
    }
}
