#!/usr/bin/env bash
# Build one store's white-label app from tenants/<key>/tenant.json.
#
#   scripts/build_tenant.sh <tenant> [apk|appbundle|ipa|all] [--debug] [--skip-assets] [--prepare-only]
#
# 1. writes the native identity: android/app/tenant.properties (applicationId, app name)
#    and ios/Flutter/Tenant.xcconfig (bundle id, display name) - both gitignored;
# 2. writes build/tenant/<key>/defines.json for --dart-define-from-file (tenant id,
#    API base URL, theme family / colour, optional Firebase client options from
#    tenants/<key>/firebase.env, never committed);
# 3. generates launcher icons (flutter_launcher_icons) and the native splash
#    (flutter_native_splash) from the tenant's images;
# 4. runs flutter build and copies the artefacts to dist/<key>/.
#
# Release signing (Android): export NOGRGR_KEYSTORE, NOGRGR_KEYSTORE_PASSWORD,
# NOGRGR_KEY_ALIAS, NOGRGR_KEY_PASSWORD. iOS signing uses the Xcode team of the machine.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
FLUTTER="${FLUTTER:-flutter}"
command -v "$FLUTTER" >/dev/null 2>&1 || FLUTTER="$HOME/flutter/bin/flutter"
DART="$(dirname "$(command -v "$FLUTTER" || echo "$FLUTTER")")/dart"
[ -x "$DART" ] || DART="dart"

usage() { sed -n '2,4p' "$0" | sed 's/^# \{0,1\}//'; exit 1; }

KEY="${1:-}"; [ -n "$KEY" ] || usage; shift
TARGET="apk"; MODE="--release"; SKIP_ASSETS=0; PREPARE_ONLY=0
for arg in "$@"; do
  case "$arg" in
    apk|appbundle|ipa|all) TARGET="$arg" ;;
    --debug) MODE="--debug" ;;
    --skip-assets) SKIP_ASSETS=1 ;;
    --prepare-only) PREPARE_ONLY=1 ;;
    *) echo "Unknown argument: $arg"; usage ;;
  esac
done

DIR="$ROOT/tenants/$KEY"
CONFIG="$DIR/tenant.json"
[ -f "$CONFIG" ] || { echo "Missing $CONFIG"; exit 1; }
command -v jq >/dev/null || { echo "jq is required"; exit 1; }

get() { jq -r --arg k "$1" '.[$k] // empty' "$CONFIG"; }
need() { local v; v="$(get "$1")"; [ -n "$v" ] || { echo "tenant.json: \"$1\" is required"; exit 1; }; printf '%s' "$v"; }

TENANT_ID="$(need tenant_id)"
APP_NAME="$(need app_name)"
ANDROID_ID="$(need android_application_id)"
IOS_ID="$(need ios_bundle_id)"
API_BASE_URL="$(need api_base_url)"
FAMILY="$(get theme_family)"; FAMILY="${FAMILY:-elora}"
VARIANT="$(get theme_variant)"; VARIANT="${VARIANT:-1}"
PRIMARY="$(need primary_color)"
SPLASH_COLOR="$(get splash_color)"; SPLASH_COLOR="${SPLASH_COLOR:-$PRIMARY}"
LOCALE="$(get default_locale)"; LOCALE="${LOCALE:-en}"
VERSION="$(get version)"; VERSION="${VERSION:-1.0.0}"
BUILD_NUMBER="$(get build_number)"; BUILD_NUMBER="${BUILD_NUMBER:-1}"
ICON="$DIR/$(need icon)"
ICON_FG="$DIR/$(get icon_foreground)"
SPLASH_IMAGE="$DIR/$(get splash_image)"

case "$FAMILY" in ecommet|elora|souqify) ;; *) echo "theme_family must be ecommet, elora or souqify"; exit 1 ;; esac
[[ "$PRIMARY" =~ ^#[0-9A-Fa-f]{6}$ ]] || { echo "primary_color must be #RRGGBB"; exit 1; }
[[ "$ANDROID_ID" =~ ^[a-z][a-z0-9_]*(\.[a-z][a-z0-9_]*)+$ ]] || { echo "android_application_id is not a valid package name"; exit 1; }
[ -f "$ICON" ] || { echo "Missing icon $ICON"; exit 1; }

OUT="$ROOT/build/tenant/$KEY"
mkdir -p "$OUT"

echo "==> $KEY: native identity"
cat > "$ROOT/android/app/tenant.properties" <<PROPS
# Generated by scripts/build_tenant.sh for "$KEY" - do not edit.
applicationId=$ANDROID_ID
appName=$APP_NAME
PROPS
cat > "$ROOT/ios/Flutter/Tenant.xcconfig" <<XC
// Generated by scripts/build_tenant.sh for "$KEY" - do not edit.
TENANT_BUNDLE_ID=$IOS_ID
TENANT_APP_NAME=$APP_NAME
XC

# Optional Firebase client options (push); absent = push stays a no-op.
FIREBASE_API_KEY=""; FIREBASE_PROJECT_ID=""; FIREBASE_SENDER_ID=""; FIREBASE_APP_ID_ANDROID=""; FIREBASE_APP_ID_IOS=""
if [ -f "$DIR/firebase.env" ]; then
  # shellcheck disable=SC1091
  set -a; . "$DIR/firebase.env"; set +a
fi

defines() {
  local platform_app_id="$1"
  jq -n \
    --arg key "$KEY" --arg tenant "$TENANT_ID" --arg name "$APP_NAME" --arg api "$API_BASE_URL" \
    --arg family "$FAMILY" --arg variant "$VARIANT" --arg primary "$PRIMARY" --arg locale "$LOCALE" \
    --arg fbApp "$platform_app_id" --arg fbKey "$FIREBASE_API_KEY" --arg fbProject "$FIREBASE_PROJECT_ID" \
    --arg fbSender "$FIREBASE_SENDER_ID" --arg ios "$IOS_ID" \
    '{TENANT_KEY:$key, TENANT_ID:$tenant, APP_NAME:$name, API_BASE_URL:$api, THEME_FAMILY:$family,
      THEME_VARIANT:$variant, PRIMARY_COLOR:$primary, DEFAULT_LOCALE:$locale, IOS_BUNDLE_ID:$ios}
     + (if $fbApp != "" then {FIREBASE_APP_ID:$fbApp, FIREBASE_API_KEY:$fbKey,
          FIREBASE_PROJECT_ID:$fbProject, FIREBASE_SENDER_ID:$fbSender} else {} end)'
}
defines "$FIREBASE_APP_ID_ANDROID" > "$OUT/defines.android.json"
defines "$FIREBASE_APP_ID_IOS" > "$OUT/defines.ios.json"

if [ "$SKIP_ASSETS" -eq 0 ]; then
  echo "==> $KEY: launcher icons + native splash"
  {
    echo "flutter_launcher_icons:"
    echo "  image_path: \"$ICON\""
    echo "  android: \"ic_launcher\""
    echo "  ios: true"
    echo "  remove_alpha_ios: true"
    echo "  min_sdk_android: 21"
    if [ -f "$ICON_FG" ]; then
      echo "  adaptive_icon_background: \"$PRIMARY\""
      echo "  adaptive_icon_foreground: \"$ICON_FG\""
    fi
  } > "$OUT/flutter_launcher_icons.yaml"
  {
    echo "flutter_native_splash:"
    echo "  color: \"$SPLASH_COLOR\""
    if [ -f "$SPLASH_IMAGE" ]; then echo "  image: \"$SPLASH_IMAGE\""; fi
    echo "  android_12:"
    echo "    color: \"$SPLASH_COLOR\""
    if [ -f "$SPLASH_IMAGE" ]; then echo "    image: \"$SPLASH_IMAGE\""; fi
    echo "  web: false"
  } > "$OUT/flutter_native_splash.yaml"
  (cd "$ROOT" && "$DART" run flutter_launcher_icons -f "$OUT/flutter_launcher_icons.yaml")
  (cd "$ROOT" && "$DART" run flutter_native_splash:create --path="$OUT/flutter_native_splash.yaml")
fi

if [ "$PREPARE_ONLY" -eq 1 ]; then
  echo "==> $KEY: prepared (defines in $OUT)"
  exit 0
fi

DIST="$ROOT/dist/$KEY"
mkdir -p "$DIST"
SUFFIX="$([ "$MODE" = "--debug" ] && echo debug || echo release)"

build() {
  local target="$1" platform="android"
  [ "$target" = "ipa" ] && platform="ios"
  echo "==> $KEY: flutter build $target $MODE"
  (cd "$ROOT" && "$FLUTTER" build "$target" "$MODE" \
    --dart-define-from-file="$OUT/defines.$platform.json" \
    --build-name="$VERSION" --build-number="$BUILD_NUMBER")
  case "$target" in
    apk) cp "$ROOT/build/app/outputs/flutter-apk/app-$SUFFIX.apk" "$DIST/$KEY-$VERSION-$SUFFIX.apk" ;;
    appbundle) cp "$ROOT/build/app/outputs/bundle/${SUFFIX}/app-${SUFFIX}.aab" "$DIST/$KEY-$VERSION-$SUFFIX.aab" ;;
    ipa) cp "$ROOT"/build/ios/ipa/*.ipa "$DIST/" ;;
  esac
}

if [ "$TARGET" = "all" ]; then
  build apk; build appbundle
  if [ "$(uname)" = "Darwin" ]; then build ipa; else echo "(ipa skipped: needs macOS + Xcode)"; fi
else
  build "$TARGET"
fi

echo "==> $KEY: done -> $DIST"
